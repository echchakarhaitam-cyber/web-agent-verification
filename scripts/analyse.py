"""Compute every reported number from the episode logs.

Writes results/summary.json and docs/results.md.
Usage:  python scripts/analyse.py results/episodes_<model1>.jsonl [episodes_<model2>.jsonl ...]

Seeds 0-9 (and later even blocks of 10) are the calibration seeds, seeds 10-19 (odd blocks) the
test seeds (docs/TASK.md). Only episodes with seed < 100 are read: pilot seeds are excluded.
"""

from __future__ import annotations

import hashlib
import json
import sys
from pathlib import Path

import numpy as np

from webverify.analysis import (
    SIGNALS,
    apply_threshold,
    arrays,
    auroc,
    bootstrap_auroc,
    brier,
    choose_threshold,
    claim_table,
    ece,
    two_proportion_z,
    wilson,
)
from webverify.tasks import BY_NAME, TASKS

ROOT = Path(__file__).resolve().parents[1]
TARGETS = (0.05, 0.10, 0.20)
DELTA = 0.05


def is_calibration(seed: int) -> bool:
    return (seed // 10) % 2 == 0


def load(path: Path) -> list[dict]:
    eps = [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line]
    return [e for e in eps if e["seed"] < 100]


def pct(x: float | None, d: int = 1) -> str:
    return "n/a" if x is None else f"{100 * x:.{d}f}%"


def ci(c) -> str:
    return "" if c is None else f" [{100 * c[0]:.1f}, {100 * c[1]:.1f}]"


def num(x: float | None, d: int = 3) -> str:
    return "n/a" if x is None else f"{x:.{d}f}"


def model_summary(eps: list[dict]) -> dict:
    k = sum(e["success"] for e in eps)
    out: dict = {"episodes": len(eps), "successes": k, "success_rate": k / len(eps),
                 "success_ci": wilson(k, len(eps)),
                 "seeds": sorted({e["seed"] for e in eps}),
                 "stops": {s: sum(e["stop"] == s for e in eps)
                           for s in ("done", "page_done", "budget", "invalid")},
                 "forced_reports": sum(e["claim_forced"] for e in eps),
                 "invalid_answers": sum(e["n_invalid"] for e in eps),
                 "steps": sum(len(e["steps"]) for e in eps),
                 "seconds_mean": float(np.mean([e["seconds"] for e in eps]))}
    out["per_task"] = {}
    for t in TASKS:
        te = [e for e in eps if e["task"] == t.name]
        kt = sum(e["success"] for e in te)
        out["per_task"][t.name] = {"n": len(te), "successes": kt,
                                   "rate": kt / len(te) if te else None,
                                   "ci": wilson(kt, len(te)),
                                   "false_success_claims": sum(
                                       bool(e["claim_success"]) and not e["success"] for e in te)}
    out["per_kind"] = {}
    for kind in ("click", "form"):
        ke = [e for e in eps if BY_NAME[e["task"]].kind == kind]
        kk = sum(e["success"] for e in ke)
        out["per_kind"][kind] = {"n": len(ke), "successes": kk, "rate": kk / len(ke),
                                 "ci": wilson(kk, len(ke))}
    out["claims"] = claim_table(eps)
    groups = [e["task"] for e in eps]
    out["signals"] = {}
    for name in SIGNALS:
        s, y = arrays(eps, name)
        out["signals"][name] = {"auroc": auroc(s, y), "auroc_ci": bootstrap_auroc(s, y, groups),
                                "brier": brier(s, y), "ece": ece(s, y),
                                "mean_success": float(s[y == 1].mean()) if (y == 1).any() else None,
                                "mean_failure": float(s[y == 0].mean()) if (y == 0).any() else None}
    out["missing"] = {"ptrue": sum(e["claim_p_true"] is None for e in eps),
                      "judge": sum(e["judge_p_yes"] is None for e in eps)}
    cal = [e for e in eps if is_calibration(e["seed"])]
    test = [e for e in eps if not is_calibration(e["seed"])]
    out["abstention"] = {"calibration_episodes": len(cal), "test_episodes": len(test),
                         "signals": {}}
    for name in SIGNALS:
        s_c, y_c = arrays(cal, name)
        s_t, y_t = arrays(test, name)
        c_c = np.array([bool(e["claim_success"]) for e in cal])
        c_t = np.array([bool(e["claim_success"]) for e in test])
        rows = {}
        for r in TARGETS:
            choice = choose_threshold(s_c, c_c, y_c, r, DELTA)
            res = apply_threshold(s_t, c_t, y_t, choice["threshold"])
            res["violation"] = res["risk"] is not None and res["risk"] > r
            rows[str(r)] = {"choice": choice, "test": res}
        # reference: accept every success claim (no abstention)
        rows["accept_all_claims"] = apply_threshold(s_t, c_t, y_t, 0.0)
        out["abstention"]["signals"][name] = rows
    return out


def render(summary: dict) -> str:
    models = summary["models"]
    names = list(models)
    L = ["# Results", "",
         "Generated by `scripts/analyse.py` from the episode logs; do not edit by hand. Protocol:",
         "[docs/TASK.md](TASK.md). Intervals are 95% (Wilson for proportions, task-level "
         "bootstrap for AUROC).", ""]
    L += ["## RQ1 -- How often does each agent succeed?", "",
          "| | " + " | ".join(names) + " |", "|---|" + "---|" * len(names)]
    L.append("| episodes | " + " | ".join(str(models[m]["episodes"]) for m in names) + " |")
    L.append("| success rate | " + " | ".join(pct(models[m]["success_rate"]) +
                                             ci(models[m]["success_ci"]) for m in names) + " |")
    for kind in ("click", "form"):
        L.append(f"| {kind} tasks | " + " | ".join(
            pct(models[m]["per_kind"][kind]["rate"]) + ci(models[m]["per_kind"][kind]["ci"])
            for m in names) + " |")
    L.append("| mean seconds per episode | " + " | ".join(
        f"{models[m]['seconds_mean']:.0f}" for m in names) + " |")
    L.append("| invalid answers / steps | " + " | ".join(
        f"{models[m]['invalid_answers']} / {models[m]['steps']}" for m in names) + " |")
    L += ["", "Per task (successes / episodes):", "",
          "| task | kind | " + " | ".join(names) + " |", "|---|---|" + "---|" * len(names)]
    for t in TASKS:
        L.append(f"| {t.name} | {t.kind} | " + " | ".join(
            f"{models[m]['per_task'][t.name]['successes']}/{models[m]['per_task'][t.name]['n']}"
            for m in names) + " |")
    if "comparison" in summary:
        L += ["", "Two-proportion z-test, larger vs smaller model: " + "; ".join(
            f"{k}: p = {num(v, 4)}" for k, v in summary["comparison"].items()) + "."]
    L += ["", "## RQ2 -- When the agent says \"success\", how often is it wrong?", "",
          "| | " + " | ".join(names) + " |", "|---|" + "---|" * len(names)]
    for key, label in (("claims_success", "success claims"),
                       ("true_success_claims", "correct success claims"),
                       ("false_success_claims", "false success claims"),
                       ("missed_successes", "successes reported as failures"),
                       ("no_report", "no usable report")):
        L.append(f"| {label} | " + " | ".join(str(models[m]["claims"][key]) for m in names) + " |")
    L.append("| false-success rate (failures among success claims) | " + " | ".join(
        pct(models[m]["claims"]["false_success_rate"]) + ci(models[m]["claims"]["false_success_ci"])
        for m in names) + " |")
    L += ["", "## RQ3 -- Which signal separates successes from failures?", "",
          "| signal | model | AUROC | Brier | ECE | mean on successes | mean on failures |",
          "|---|---|---|---|---|---|---|"]
    for sig in SIGNALS:
        for m in names:
            v = models[m]["signals"][sig]
            a = num(v["auroc"]) + ("" if v["auroc_ci"] is None else
                                   f" [{v['auroc_ci'][0]:.3f}, {v['auroc_ci'][1]:.3f}]")
            L.append(f"| {sig} | {m} | {a} | {num(v['brier'])} | {num(v['ece'])} | "
                     f"{num(v['mean_success'])} | {num(v['mean_failure'])} |")
    L += ["", "Signals: `claim` = the agent's yes/no report; `verbal` = its stated confidence as "
          "P(success); `ptrue` = token probability of `true` in its report; `judge` = P(Yes) of an "
          "independent judge prompt on the final page (same model). Missing values: " + "; ".join(
              f"{m}: ptrue {models[m]['missing']['ptrue']}, judge {models[m]['missing']['judge']}"
              for m in names) + "."]
    L += ["", "## RQ4 -- Abstention: accept a success claim only if the signal is high enough", "",
          "Thresholds certified on the calibration seeds (risk among accepted <= r* with "
          f"probability >= {1 - DELTA:.0%}, Bonferroni over 20 thresholds), applied to the test "
          "seeds. Coverage = share of all test episodes accepted automatically; risk = share of "
          "accepted episodes that failed. **Bold** marks a test risk above the target.", ""]
    for m in names:
        ab = models[m]["abstention"]
        L += [f"### {m} ({ab['calibration_episodes']} calibration / {ab['test_episodes']} "
              "test episodes)", "",
              "| signal | accept every success claim | " + " | ".join(
                  f"r* = {pct(r, 0)}" for r in TARGETS) + " |",
              "|---|---|" + "---|" * len(TARGETS)]
        for sig in SIGNALS:
            rows = ab["signals"][sig]
            base = rows["accept_all_claims"]
            cells = [f"coverage {pct(base['coverage'])}, risk {pct(base['risk'])}"]
            for r in TARGETS:
                row = rows[str(r)]
                if not row["choice"]["certified"]:
                    cells.append("not certifiable (abstain on all)")
                    continue
                t = row["test"]
                risk = pct(t["risk"])
                if t["violation"]:
                    risk = f"**{risk}**"
                cells.append(f"t = {row['choice']['threshold']:.2f}: coverage "
                             f"{pct(t['coverage'])}, risk {risk}{ci(t['risk_ci'])}")
            L.append(f"| {sig} | " + " | ".join(cells) + " |")
        L.append("")
    L += ["## Model files", ""] + [f"- `{m}`: sha256 `{h}`" for m, h in
                                   summary["model_sha256"].items()]
    return "\n".join(L).rstrip() + "\n"


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def main() -> int:
    paths = [Path(p) for p in sys.argv[1:]]
    if not paths:
        print(__doc__)
        return 2
    summary: dict = {"models": {}, "model_sha256": {}}
    eps_by_model = {}
    for p in paths:
        eps = load(p)
        name = eps[0]["model"]
        eps_by_model[name] = eps
        summary["models"][name] = model_summary(eps)
    model_dir = ROOT.parent / "models"
    for name in summary["models"]:
        f = model_dir / f"{name}.gguf"
        summary["model_sha256"][name] = sha256(f) if f.exists() else "NOT MEASURED"
    if len(eps_by_model) == 2:
        small, large = sorted(eps_by_model, key=lambda n: summary["models"][n]["success_rate"])
        comp = {}
        for kind in ("all", "click", "form"):
            def ks(n, kind=kind):
                e = [x for x in eps_by_model[n] if kind == "all" or BY_NAME[x["task"]].kind == kind]
                return sum(x["success"] for x in e), len(e)
            comp[kind] = two_proportion_z(*ks(large), *ks(small))
        summary["comparison"] = comp
    (ROOT / "results").mkdir(exist_ok=True)
    (ROOT / "results" / "summary.json").write_text(
        json.dumps(summary, indent=2, sort_keys=True) + "\n", encoding="utf-8", newline="\n")
    (ROOT / "docs" / "results.md").write_text(render(summary), encoding="utf-8", newline="\n")
    print("wrote results/summary.json and docs/results.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
